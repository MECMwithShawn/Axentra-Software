const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
(async()=>{
  const root=path.resolve(__dirname,'..');
  const browser=await chromium.launch({channel:process.env.AXENTRA_BROWSER==='chromium'?undefined:'msedge',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('file:///'+path.join(root,'out/axentra-motion-preview.html').replaceAll('\\','/'));
  await page.waitForFunction(()=>window.axentraDemo?.getState().items.every(x=>x.loaded));
  let s=await page.evaluate(()=>{axentraDemo.setPaused(true);axentraDemo.seek(0);return axentraDemo.getState();});
  assert.equal(s.renderer,'webgl');assert.equal(s.items.length,9);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:path.join(root,'out/desktop.png')});
  const ghost=page.locator('[data-app="ghost"]');
  await ghost.hover();
  await page.waitForFunction(()=>axentraDemo.getState().items.find(x=>x.id==='ghost').hover>1.04);
  s=await page.evaluate(()=>axentraDemo.getState());
  assert(s.items.find(x=>x.id==='ghost').hover>1.04,'spring overshoots target');
  await page.screenshot({path:path.join(root,'out/hover.png')});
  const before=s.items.find(x=>x.id==='ghost').yaw;
  await ghost.click();
  await page.waitForFunction(v=>axentraDemo.getState().items.find(x=>x.id==='ghost').yaw>v+1,before);
  const mid=await page.evaluate(()=>axentraDemo.getState().items.find(x=>x.id==='ghost'));
  assert(Math.abs(mid.bend)>.2,'spin deforms the mesh');
  await page.screenshot({path:path.join(root,'out/bend.png')});
  await page.mouse.move(10,10);
  await page.evaluate(()=>axentraDemo.seek(12.22));
  const back=await page.evaluate(()=>axentraDemo.getState().items.find(x=>x.id==='pdf'));
  assert(Math.cos(back.yaw)<-.9,'PDF reverse face is exposed for mirrored-artwork review');
  await page.screenshot({path:path.join(root,'out/reverse.png')});
  await page.locator('[data-app="archive"]').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#status').textContent(),'Axentra Archive');
  await page.setViewportSize({width:390,height:980});
  await page.evaluate(()=>axentraDemo.seek(0));
  await page.waitForTimeout(100);
  const boxes=await page.locator('.axm-target').evaluateAll(els=>els.map(e=>e.getBoundingClientRect().toJSON()));
  for(const b of boxes){assert(b.left>=0 && b.right<=390,`button fits mobile: ${JSON.stringify(b)}`);}
  const hostBox=await page.locator('#scene').boundingBox();
  const archiveBox=await page.locator('[data-app="archive"]').boundingBox();
  assert.equal(boxes.length,9);
  assert(Math.abs(archiveBox.x+archiveBox.width/2-195)<1,'Archive centered on the fifth mobile row');
  for(const b of boxes) assert(b.top>=hostBox.y && b.bottom<=hostBox.y+hostBox.height,'All nine targets fit the host height');
  const archiveLabel=await page.locator('[data-app="archive"] .axm-label').boundingBox();
  assert(archiveLabel.y+archiveLabel.height<=hostBox.y+hostBox.height,'Archive label is not clipped');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  await page.screenshot({path:path.join(root,'out/mobile.png'),fullPage:true});
  const reduced=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  await reduced.goto(page.url());await reduced.waitForFunction(()=>!!window.axentraDemo);
  const r1=await reduced.evaluate(()=>axentraDemo.getState());
  await reduced.waitForTimeout(200);
  const r2=await reduced.evaluate(()=>axentraDemo.getState());
  assert.equal(r1.time,0);assert.equal(r2.time,0);
  assert(r2.items.every(x=>x.bend===0 && x.yaw===0 && x.twist===0));
  assert.equal(await reduced.locator('#pause').isVisible(),false);
  const staticPage=await browser.newPage({viewport:{width:390,height:980}});
  await staticPage.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type==='webgl'?null:original.call(this,type,...args);};});
  await staticPage.goto(page.url());await staticPage.waitForFunction(()=>!!window.axentraDemo);
  assert.equal(await staticPage.evaluate(()=>axentraDemo.getState().renderer),'static');
  assert.equal(await staticPage.locator('.axm-fallback:visible').count(),9);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(root,'out/validation.json'),JSON.stringify({renderer:'webgl',icons:9,hoverOvershoot:true,deformation:true,keyboard:true,mobileWidth:390,reducedMotion:true,staticFallback:true,errors},null,2));
  await browser.close();console.log('Passed: textures, hover spring, bend, keyboard, mobile, reduced motion, WebGL fallback.');
})().catch(e=>{console.error(e);process.exit(1)});
